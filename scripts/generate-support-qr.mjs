// Generates QR codes for the support links in src/support.ts.
// Run with: npm run qr   (again after any handle in src/support.ts changes)
//
// The codes are drawn at build time and committed as plain path data, so the
// app shows them with the wifi off and ships no QR library to the browser.
// `qrcode` is a devDependency used only here. A test fails if a handle changes
// and this script was not re-run.
import QRCode from 'qrcode';
import { readFileSync, writeFileSync } from 'node:fs';

const src = readFileSync(new URL('../src/support.ts', import.meta.url), 'utf8');
const handle = (name) => src.match(new RegExp(`export const ${name} = '([^']*)'`))?.[1] ?? '';

const urls = [];
const kofi = handle('KOFI_HANDLE');
const venmo = handle('VENMO_HANDLE');
if (kofi) urls.push(`https://ko-fi.com/${kofi}`);
if (venmo) urls.push(`https://venmo.com/u/${venmo}`);

const entries = urls.map((url) => {
  const qr = QRCode.create(url, { errorCorrectionLevel: 'M' });
  const { size, data } = qr.modules;
  let path = '';
  for (let y = 0; y < size; y++) {
    for (let x = 0; x < size; x++) {
      if (data[y * size + x]) path += `M${x} ${y}h1v1h-1z`;
    }
  }
  return `  ${JSON.stringify(url)}: { size: ${size}, path: ${JSON.stringify(path)} },`;
});

const out = `// GENERATED by scripts/generate-support-qr.mjs. Do not edit by hand; run \`npm run qr\`.
// One QR code per support URL, as SVG path data on a 1-unit module grid.

export const SUPPORT_QR: Record<string, { size: number; path: string }> = {
${entries.join('\n')}
};
`;
writeFileSync(new URL('../src/supportQr.ts', import.meta.url), out);
console.log(`Wrote ${urls.length} QR code(s): ${urls.join(', ')}`);
